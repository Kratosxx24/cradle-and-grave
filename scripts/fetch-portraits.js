// Looks up each figure's Wikipedia article and writes data/portraits.js with the
// lead image and article link. Run with: npm run portraits
// Re-run after adding figures; existing entries are refetched too.
const fs = require("fs");
const path = require("path");
const { POOL } = require("../js/figures.js");

// Article titles where the figure's display name doesn't land on the right page.
const TITLES = {
  "Cleopatra VII": "Cleopatra",
  "Jesus of Nazareth": "Jesus",
  "Siddhartha Gautama": "The Buddha",
  "Archduke Franz Ferdinand": "Archduke Franz Ferdinand of Austria",
  "Richard the Lionheart": "Richard I of England",
  "Elizabeth I": "Elizabeth I",
  "Elizabeth II": "Elizabeth II",
  "Henry VIII": "Henry VIII",
  "Saint Peter": "Saint Peter",
  "Augustus": "Augustus",
  "Hannibal": "Hannibal",
  "James Cook": "James Cook",
  "Mahatma Gandhi": "Mahatma Gandhi",
  "Diego Maradona": "Diego Maradona",
};

// Figures whose article image shouldn't be shown as a portrait.
const SKIP = new Set(["Muhammad"]); // depictions are traditionally avoided

const UA = "LifelinesGame/1.0 (https://github.com/Kratosxx24/lifelines)";
const sleep = ms => new Promise(r => setTimeout(r, ms));

async function lookup(title) {
  const url = "https://en.wikipedia.org/api/rest_v1/page/summary/" + encodeURIComponent(title.replace(/ /g, "_"));
  const res = await fetch(url, { headers: { "User-Agent": UA, "Api-User-Agent": UA } });
  if (!res.ok) throw new Error(`${res.status} for ${title}`);
  return res.json();
}

(async () => {
  const out = {}, problems = [];
  for (const fig of POOL) {
    const name = fig[0];
    const title = TITLES[name] || name;
    try {
      const s = await lookup(title);
      const page = s.content_urls && s.content_urls.desktop.page;
      if (s.type === "disambiguation") { problems.push(`${name}: "${title}" is a disambiguation page`); continue; }
      const thumb = s.thumbnail && s.thumbnail.source;
      out[name] = {
        img: SKIP.has(name) || !thumb ? null : thumb.split("?")[0], // the API picks a size Wikimedia serves; other widths 400
        page,
        title: s.title,
      };
      if (!out[name].img && !SKIP.has(name)) problems.push(`${name}: no image on "${s.title}"`);
    } catch (e) {
      problems.push(`${name}: ${e.message}`);
    }
    await sleep(120);
  }

  const body = "// Generated by scripts/fetch-portraits.js from Wikipedia. Do not edit by hand.\n" +
    "(function (CG) {\n  CG.PORTRAITS = " + JSON.stringify(out, null, 2).replace(/\n/g, "\n  ") + ";\n" +
    "})(typeof window !== \"undefined\" ? (window.CG = window.CG || {}) : module.exports);\n";
  fs.writeFileSync(path.join(__dirname, "..", "data", "portraits.js"), body);
  console.log(`Wrote ${Object.keys(out).length} of ${POOL.length} figures.`);
  if (problems.length) console.log("Check these:\n  " + problems.join("\n  "));
})();
